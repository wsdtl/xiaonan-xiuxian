def main() -> None:
    changed = 0
    for path in sorted(WORLD.rglob("*.json")):
        if not path.name.endswith(("炼器工匠.json", "炼丹师.json", "阵师.json")):
            continue
        value = json.loads(path.read_text(encoding="utf-8"))
        rows = value if isinstance(value, list) else []
        for row in rows:
            style = str(row.get("话语风格") or "").strip()
            if style not in PROFILES:
                raise ValueError(f"未定义主持人话语风格：{path} -> {style}")
            first, ready, missing, done = PROFILES[style]
            noun = "器律" if "炼器工匠" in path.name else "丹药" if "炼丹师" in path.name else "阵法"
            action = "铸" if noun == "器律" else "炼" if noun == "丹药" else "布"
            row["话语"] = {
                "总览": f"{{主持}}道：{first}今日要{action}哪一道{noun}？",
                "审材": "{主持}逐项验过材料，先把火候与根脚核清。",
                "齐备": ready,
                "不足": missing,
                "完成": done,
            }
        if rows:
            path.write_text(json.dumps(rows, ensure_ascii=False, indent=2) + "\n", encoding="utf-8")
            changed += 1
    print(f"已补齐主持人话语：{changed} 个地点文件")


if __name__ == "__main__":
    main()
