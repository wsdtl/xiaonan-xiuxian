def _default_hint(command: str) -> str:
    parts = str(command or "").strip().split(maxsplit=1)
    head = parts[0] if parts else ""
    if head in {"帮助", "help"}:
        return "发送「帮助 <分类>」查看该分类下的全部命令。"
    if head:
        return f"发送「帮助 {head}」查看完整写法与后续步骤。"
    return "发送「帮助」查看可用命令与后续步骤。"


def closing_for(command: str) -> str:
    """按命令来源模块取业务结尾；未登记模块才退回通用帮助提示。"""

    parts = str(command or "").strip().split(maxsplit=1)
    head = parts[0] if parts else ""
    entry = help_registry.find(head) if head else None
    if entry is not None:
        hint = CLOSING_BY_MODULE.get(entry.source_module)
        if hint:
            return hint
    return _default_hint(head)


